    private fun devHeaders(): Map<String, String> = mapOf(
        "X-Dev-Auth" to "true", "X-Dev-Tenant-Id" to "1", "X-Dev-Roles" to "titlis.admin",
    )

    @Test
    fun `tree depth all monta produtos times servicos com DAG e piso critico`() = testApplication {
        val authenticator = testRequestAuthenticator()
        application {
            installTestSecurity(authenticator)
            reliabilityRoutes(ReliabilityRepository())
        }

        val res = client.get("/v1/reliability/tree?depth=all") { devHeaders().forEach { (k, v) -> header(k, v) } }
        assertEquals(HttpStatusCode.OK, res.status)
        val body = res.bodyAsText()

        assertContains(body, "checkout")
        assertContains(body, "onboarding")
        // DAG: team-pag sob os dois produtos
        assertContains(body, "\"path\":\"checkout/team-pag\"")
        assertContains(body, "\"path\":\"onboarding/team-pag\"")
        // folhas
        assertContains(body, "orders-api")
        assertContains(body, "ledger")
        assertContains(body, "signup")
        // piso crítico (orders-api tier-1 @40)
        assertContains(body, "\"criticalBreach\":true")
    }

    @Test
    fun `tree depth 1 retorna so produtos sem times`() = testApplication {
        val authenticator = testRequestAuthenticator()
        application {
            installTestSecurity(authenticator)
            reliabilityRoutes(ReliabilityRepository())
        }

        val res = client.get("/v1/reliability/tree?depth=1") { devHeaders().forEach { (k, v) -> header(k, v) } }
        assertEquals(HttpStatusCode.OK, res.status)
        val body = res.bodyAsText()
        assertContains(body, "checkout")
        assertFalse(body.contains("team-pag"), "depth=1 não deve expor times")
    }

    @Test
    fun `findings do servico lista workload e queue com pts recuperaveis`() = testApplication {
        val authenticator = testRequestAuthenticator()
        application {
            installTestSecurity(authenticator)
            reliabilityRoutes(ReliabilityRepository())
        }

        val res = client.get("/v1/reliability/services/10/findings") { devHeaders().forEach { (k, v) -> header(k, v) } }
        assertEquals(HttpStatusCode.OK, res.status)
        val body = res.bodyAsText()
        assertContains(body, "SEC-003")
        assertContains(body, "QS-001")
        assertContains(body, "riGainService")
        // deep-link de remediação: o finding de workload carrega o k8s_uid
        assertContains(body, "uid-orders")
    }

    @Test
    fun `trend retorna pontos diarios ponderados por tier`() = testApplication {
        val authenticator = testRequestAuthenticator()
        application {
            installTestSecurity(authenticator)
            reliabilityRoutes(ReliabilityRepository())
        }

        val res = client.get("/v1/reliability/trend?root=checkout/team-pag&days=30") { devHeaders().forEach { (k, v) -> header(k, v) } }
        assertEquals(HttpStatusCode.OK, res.status)
        val body = res.bodyAsText()
        assertContains(body, "\"ri\"")
        assertContains(body, "\"date\"")
        // dois dias distintos → dois pontos
        assertEquals(2, body.split("\"date\"").size - 1)
    }

    @Test
    fun `tree exige autenticacao`() = testApplication {
        val authenticator = testRequestAuthenticator()
        application {
            installTestSecurity(authenticator)
            reliabilityRoutes(ReliabilityRepository())
        }
        val res = client.get("/v1/reliability/tree")
        assertEquals(HttpStatusCode.Unauthorized, res.status)
    }
}
