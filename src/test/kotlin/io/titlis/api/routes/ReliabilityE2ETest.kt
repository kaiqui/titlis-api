// Unidade pura do rollup — pesos e poda, sem banco.
class ReliabilityRollupUnitTest {

    @Test
    fun `tierWeight mapeia tiers para pesos`() {
        assertEquals(3.0, ReliabilityRepository.tierWeight("tier-1"))
        assertEquals(3.0, ReliabilityRepository.tierWeight("HIGH"))
        assertEquals(2.0, ReliabilityRepository.tierWeight("tier-2"))
        assertEquals(1.0, ReliabilityRepository.tierWeight(null))
        assertEquals(1.0, ReliabilityRepository.tierWeight("tier-3"))
    }

    @Test
    fun `sliceTree poda filhos por depth e acha por path`() {
        val service = ReliabilityNodeDTO(path = "checkout/team/10", kind = "service", name = "svc", hasChildren = true)
        val team = ReliabilityNodeDTO(path = "checkout/team", kind = "team", name = "team", hasChildren = true, children = listOf(service))
        val product = ReliabilityNodeDTO(path = "checkout", kind = "product", name = "checkout", hasChildren = true, children = listOf(team))
        val root = ReliabilityNodeDTO(path = "", kind = "estate", name = "Estate", hasChildren = true, children = listOf(product))

        // depth=1 a partir da raiz → só produtos, sem times
        val d1 = ReliabilityRepository.sliceTree(root, "", 1)!!
        assertEquals(1, d1.children.size)
        assertTrue(d1.children.first().children.isEmpty())

        // navega até o produto, depth=1 → times aparecem
        val prod = ReliabilityRepository.sliceTree(root, "checkout", 1)!!
        assertEquals("product", prod.kind)
        assertEquals(1, prod.children.size)
        assertEquals("team", prod.children.first().kind)

        // path inexistente → null
        assertEquals(null, ReliabilityRepository.sliceTree(root, "nope", 1))
    }
}

